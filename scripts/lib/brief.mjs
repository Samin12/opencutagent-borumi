// Pure job logic ported from OpenCutAgent server/animation/jobs.js: manifest generation, the
// Scene.tsx scaffold, the brief.md and words.json builders, size and duration rules, the
// render.json sentinel reader, jobTitle. Plus the Borumi adapters: get_transcript responses
// (layers[].segments[].items triples in project ms) become the brief's narration lines, the
// words.json list and the context transcript.
//
// Nothing here touches the network or spawns anything; the CLI in scripts/job.mjs does the IO.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { round3, mmss, mmssMs, mmssMsPrecise } from "./fmt.mjs";

/** Jobs are always 30 fps compositions: the kit's SEC()/SCENE() hardcode 30 and Borumi conforms imports. */
export const FPS = 30;

export const RAW_MIN_SEC = 0.5, RAW_MAX_SEC = 600, RAW_DEFAULT_SEC = 5;
/** Segment jobs shorter than this are refused (upstream rule). */
export const MIN_JOB_SEC = 0.5;

export function newJobId(now = Date.now()) {
  return "anim-" + now.toString(36);
}

/**
 * A human title for a job, at most `max` characters: derived from the selected narration at
 * creation, replaced by the agent's own name for the animation once it builds one
 * (render.json "title"). Pure.
 */
export function jobTitle(text, max = 20) {
  const t = String(text == null ? "" : text).replace(/\s+/g, " ").trim();
  if (!t) return "Animation";
  if (t.length <= max) return t;
  const cut = t.slice(0, max - 1);
  const sp = cut.lastIndexOf(" ");
  return (sp > Math.floor(max / 2) ? cut.slice(0, sp) : cut).trimEnd() + "…";
}

/**
 * Validate a chosen output size. Returns {width,height} rounded DOWN to even numbers (h264
 * yuv420p refuses odd dimensions) or null when the values are not a usable size. Pure.
 */
export function normalizeSizeOverride(w, h) {
  const W = Math.round(Number(w)), H = Math.round(Number(h));
  if (!Number.isFinite(W) || !Number.isFinite(H)) return null;
  if (W < 16 || H < 16 || W > 8192 || H > 8192) return null;
  return { width: W - (W % 2), height: H - (H % 2) };
}

/** Raw-length validation in seconds, round3; null on garbage or out of range. Pure. */
export function normalizeRawDuration(sec) {
  const n = Number(sec);
  if (!Number.isFinite(n) || n < RAW_MIN_SEC || n > RAW_MAX_SEC) return null;
  return round3(n);
}

/**
 * Whole frames that fit inside [startMs, endMs]: floor, never round, so the render is never
 * longer than the range it replaces. Pure.
 */
export function durationInFramesFor(startMs, endMs, fps = FPS) {
  const ms = Number(endMs) - Number(startMs);
  if (!Number.isFinite(ms) || ms <= 0) return 0;
  return Math.floor((ms * fps) / 1000 + 1e-9);
}

/** The job's effective end: start + the rendered length, rounded down to whole ms. Pure. */
export function endMsEffectiveFor(startMs, durationInFrames, fps = FPS) {
  return Number(startMs) + Math.floor((durationInFrames * 1000) / fps);
}

/** Borumi's canvas preset from a size when the caller did not name one. Pure. */
export function inferCanvasFormat(width, height) {
  const w = Number(width), h = Number(height);
  if (!(w > 0) || !(h > 0)) return "custom";
  if (w === h) return "square";
  return w > h ? "landscape" : "vertical";
}

/* ============================ manifest ============================ */

const ident = (id) => "Scene_" + String(id).replace(/[^A-Za-z0-9_]/g, "_");

/** Source of the generated src/jobs/manifest.ts for these job entries. Pure. */
export function manifestSource(entries) {
  const lines = [
    "/**",
    " * AUTO-GENERATED by scripts/job.mjs. Do not edit by hand: the script",
    " * rewrites this file whenever a job is created or removed. Each job folder",
    " * (`src/jobs/<id>/`) owns its `Scene.tsx`; this file only registers them.",
    " */",
    'import type { JobEntry } from "./types";',
  ];
  for (const e of entries) lines.push(`import ${ident(e.id)} from "./${e.id}/Scene";`);
  lines.push("", "export const jobs: JobEntry[] = [");
  for (const e of entries) {
    lines.push(
      `  { id: ${JSON.stringify(e.id)}, component: ${ident(e.id)}, fps: ${e.fps}, width: ${e.width}, height: ${e.height}, durationInFrames: ${e.durationInFrames} },`
    );
  }
  lines.push("];", "");
  return lines.join("\n");
}

/** Rewrite the workspace manifest from the job folders actually on disk. Returns the entry count. */
export function regenerateManifest(dir) {
  const jobsDir = join(dir, "src", "jobs");
  const entries = [];
  let names = [];
  try { names = readdirSync(jobsDir, { withFileTypes: true }); } catch { names = []; }
  for (const e of names) {
    if (!e.isDirectory()) continue;
    const jp = join(jobsDir, e.name, "job.json");
    const sp = join(jobsDir, e.name, "Scene.tsx");
    if (!existsSync(jp) || !existsSync(sp)) continue;
    try {
      const j = JSON.parse(readFileSync(jp, "utf8"));
      if (j && j.id === e.name && j.fps > 0 && j.width > 0 && j.height > 0 && j.durationInFrames > 0) {
        entries.push({ id: j.id, fps: j.fps, width: j.width, height: j.height, durationInFrames: j.durationInFrames });
      }
    } catch { /* skip a corrupt job folder */ }
  }
  entries.sort((a, b) => a.id.localeCompare(b.id));
  writeFileSync(join(jobsDir, "manifest.ts"), manifestSource(entries));
  return entries.length;
}

